import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { readFile } from 'node:fs/promises'
import { validateEvent, parseEventsBackup } from '../src/eventStore.js'

const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
const nav = name => page.locator('.sidebar nav').getByRole('button', { name, exact: true }).click()
const saveDownload = async (button, path) => { const pending = page.waitForEvent('download'); await button.click(); await (await pending).saveAs(path); return readFile(path, 'utf8') }
const noOverflow = async () => assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'Page overflows horizontally')
try {
  await page.goto('http://127.0.0.1:5173')
  await page.locator('.home-total-value').waitFor()
  await nav('시설 비교')
  await page.locator('.compare-main').nth(2).waitFor()
  assert.equal(await page.locator('.compare-card').count(), 3)
  await page.getByLabel('시설 선택 1', { exact: true }).selectOption('농업박물관')
  await page.getByLabel('연령', { exact: true }).selectOption('20대')
  await page.getByLabel('성별', { exact: true }).selectOption('F')
  await page.locator('.compare-main').nth(2).waitFor()
  await page.waitForFunction(() => !document.querySelector('.compare-card [role=status]'))
  const response = await page.request.get('http://127.0.0.1:8000/api/dashboard?facility=농업박물관&age=20대&sex=F')
  const data = await response.json()
  const avg = Number((await page.locator('.compare-main strong').first().innerText()).replace(/[^\d.]/g,''))
  assert.ok(Math.abs(avg - data.summary.population / data.summary.observed_days) < .06)
  const csv = await saveDownload(page.getByRole('button', { name: '이 시설 비교값 CSV', exact: true }).first(), '/tmp/compare.csv')
  assert.ok(csv.includes('농업박물관') && csv.includes('20대'))
  await page.screenshot({ path: '/tmp/operations-compare.png', fullPage: true })
  await nav('행사 전후 분석')
  await page.getByRole('button', { name: '+ 일정 등록', exact: true }).click()
  await page.getByLabel('일정 이름', { exact: true }).fill('검증용 행사 (실제 행사 아님)')
  await page.getByLabel('시설', { exact: true }).selectOption('농업박물관')
  await page.getByLabel('시작일', { exact: true }).fill('2025-06-01')
  await page.getByLabel('종료일', { exact: true }).fill('2025-06-07')
  await page.getByLabel('운영 메모', { exact: true }).fill('자동 검증용 기록\n원자료로 전후 집계 확인')
  await page.getByRole('button', { name: '일정 저장', exact: true }).click()
  await page.locator('.event-result').waitFor()
  assert.equal(await page.locator('.event-period').count(), 3)
  assert.ok(!(await page.locator('.event-result strong').innerText()).includes('—'))
  await saveDownload(page.getByRole('button', { name: '분석 CSV 다운로드', exact: true }), '/tmp/event-analysis.csv')
  const backup = await saveDownload(page.getByRole('button', { name: '일정 백업', exact: true }), '/tmp/event-backup.json')
  assert.equal(parseEventsBackup(backup).length, 1)
  assert.equal(validateEvent({ ...parseEventsBackup(backup)[0], end: '2025-02-30' }), false)
  await page.screenshot({ path: '/tmp/operations-event.png', fullPage: true })
  await page.reload()
  await nav('행사 전후 분석')
  await page.locator('.event-result').waitFor()
  assert.equal(await page.locator('.event-list-item').count(), 1)
  await page.getByRole('button', { name: '수정', exact: true }).click()
  await page.getByLabel('일정 이름', { exact: true }).fill('수정 검증 기록')
  await page.getByRole('button', { name: '일정 저장', exact: true }).click()
  await page.getByRole('button', { name: '운영 캘린더 보기', exact: true }).click()
  await page.getByLabel('캘린더 월', { exact: true }).fill('2025-06')
  await page.getByRole('button', { name: '2025-06-03, 일정 1개', exact: true }).click()
  assert.ok((await page.locator('.calendar-detail').innerText()).includes('수정 검증 기록'))
  await page.screenshot({ path: '/tmp/operations-calendar.png', fullPage: true })
  await page.locator('.calendar-detail-item').click()
  await page.locator('.event-result').waitFor()
  // Future records must stay pending; don't manufacture analytics.
  await page.getByRole('button', { name: '수정', exact: true }).click()
  await page.getByLabel('시작일', { exact: true }).fill('2027-02-01')
  await page.getByLabel('종료일', { exact: true }).fill('2027-02-03')
  await page.getByRole('button', { name: '일정 저장', exact: true }).click()
  await page.getByText('분석 대기: 해당 시설의 제공 데이터 기간 밖입니다.', { exact: true }).first().waitFor()
  assert.equal(await page.locator('.event-result strong').innerText(), '—')
  // All three mobile screens must fit a narrow phone.
  await page.setViewportSize({ width: 390, height: 844 })
  await noOverflow()
  await page.screenshot({ path: '/tmp/operations-mobile-event.png', fullPage: true })
  await nav('운영 캘린더')
  await noOverflow()
  await page.screenshot({ path: '/tmp/operations-mobile-calendar.png', fullPage: true })
  await nav('시설 비교')
  await page.locator('.compare-main').nth(2).waitFor()
  await noOverflow()
  await page.screenshot({ path: '/tmp/operations-mobile-compare.png', fullPage: true })
  await nav('행사 전후 분석')
  await page.getByRole('button', { name: '삭제', exact: true }).click()
  await page.getByRole('button', { name: '삭제 확인', exact: true }).click()
  assert.equal(await page.locator('.event-list-item').count(), 0)
  await page.locator('input[type=file]').setInputFiles('/tmp/event-backup.json')
  await page.locator('.event-list-item').waitFor()
  await page.locator('input[type=file]').setInputFiles('/tmp/event-backup.json')
  assert.equal(await page.locator('.event-list-item').count(), 1)
  // API failure and retry use the actual UI, preserving the event record.
  await page.route('**/api/events/analysis?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"검증용 연결 오류"}' }))
  await page.getByLabel('전후 비교 기간', { exact: true }).selectOption('7')
  await page.getByText('검증용 연결 오류', { exact: true }).waitFor()
  await page.unroute('**/api/events/analysis?**')
  await page.getByRole('button', { name: '다시 시도', exact: true }).click()
  await page.locator('.event-result').waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: comparison values, CSV, event CRUD/persistence/backup, calendar navigation, pending data, mobile layouts, error/retry, no runtime errors')
} finally { await browser.close() }
