  await page.locator('.facility-relation-card .rank-expand, .facility-relation-card .facility-rank-list').first().waitFor()
  const relationCsv = await download(page.locator('.facility-relation-card').getByRole('button', { name: '집계 CSV 다운로드', exact: true }), '/tmp/culture-relations.csv')
  assert.ok(relationCsv.includes('20·30대'))
  assert.equal(relationCsv.includes('undefined'), false)
  await nav('실행 계획')
  await page.setViewportSize({ width: 320, height: 740 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  assert.equal(await page.locator('.sidebar nav button span').first().isVisible(), true)
  await page.screenshot({ path: '/tmp/culture-improvements-mobile.png', fullPage: true, animations: 'disabled' })
  assert.deepEqual(errors, [])
  console.log('Improvement checks passed: drafts, filters, navigation, focus, PDF, archive, search, sort, backup and CSV.')
