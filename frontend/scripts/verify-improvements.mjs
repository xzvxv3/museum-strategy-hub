  assert.equal(await page.locator('.saved-plan-card').count(), 1)
  await page.getByLabel('계획 정렬').selectOption('due')
  const backupText = await download(page.getByRole('button', { name: '백업 다운로드', exact: true }), '/tmp/culture-plans-backup.json')
  const backup = JSON.parse(backupText)
  assert.equal(Object.keys(parseBackup(backupText)).length, 1)
  assert.throws(() => parseBackup('{"format":"culture-plans","version":1,"plans":{"bad":{}}}'))
  await page.locator('input[type="file"]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await page.getByRole('status').filter({ hasText: '백업 파일을 선택' }).waitFor()
  await page.evaluate(() => localStorage.removeItem('culture-execution-plans-v1'))
  await page.locator('input[type="file"]').setInputFiles('/tmp/culture-plans-backup.json')
  await page.getByRole('status').filter({ hasText: '1개 계획을 가져왔습니다.' }).waitFor()
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('culture-execution-plans-v1'))), backup.plans)
  await page.locator('input[type="file"]').setInputFiles('/tmp/culture-plans-backup.json')
  await page.getByRole('status').filter({ hasText: '기존 계획 1개는 유지' }).waitFor()
  await nav('데이터 분석')
  await page.locator('.kpi').first().waitFor()
